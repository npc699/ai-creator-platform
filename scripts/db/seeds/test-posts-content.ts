export type SeedPostTemplate = {
  title: string;
  tags: string[];
  daysAgo: number;
  paragraphs: string[];
};

export type AccountPostTemplate = {
  label: string;
  posts: SeedPostTemplate[];
};

const MIN_POST_CHARS = 400;
const MAX_POST_CHARS = 500;

const LENGTH_PADDING = [
  "发布之后我会复盘阅读完成率、收藏率和留言区反馈，记录哪些表达真正触达读者，并把结论写进下一篇的选题备忘与结构提纲里。",
  "我更建议先把一个栏目连续更新至少四周，再考虑换工具或换平台。稳定节奏会同时帮助读者和推荐系统建立预期。",
  "写作过程中保留原始提纲与修改记录同样重要，团队复盘时可以快速判断问题出在选题、结构还是表达层面，而不是重复踩坑。",
];

function countPlainChars(paragraphs: string[]) {
  return paragraphs.join("").replace(/\s+/g, "").length;
}

function normalizePostLength(post: SeedPostTemplate): SeedPostTemplate {
  const paragraphs = [...post.paragraphs];
  let padIndex = 0;

  while (countPlainChars(paragraphs) < MIN_POST_CHARS) {
    paragraphs.push(LENGTH_PADDING[padIndex % LENGTH_PADDING.length]);
    padIndex += 1;

    if (padIndex > LENGTH_PADDING.length * 3) {
      throw new Error(`[${post.title}] 无法扩写到 ${MIN_POST_CHARS} 字`);
    }
  }

  const count = countPlainChars(paragraphs);
  if (count > MAX_POST_CHARS) {
    throw new Error(`[${post.title}] 正文字数 ${count}，超过 ${MAX_POST_CHARS} 字`);
  }

  return { ...post, paragraphs };
}

function normalizeAccountTemplates(templates: AccountPostTemplate[]) {
  return templates.map((account) => ({
    ...account,
    posts: account.posts.map((post) => normalizePostLength(post)),
  }));
}

